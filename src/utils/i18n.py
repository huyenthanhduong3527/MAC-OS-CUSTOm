# -----------------------------------------------------------------------------
# Runtime Internationalization State Manager
# -----------------------------------------------------------------------------
class I18nManager:
    def __init__(self):
        self._current_lang = "vi"
        self._preferred_languages: List[str] = ["vi", "en"]
        self._listeners: List[Callable[[str], None]] = []
        self._file_monitor = None
        self._load_from_config()
        self._setup_file_monitor()

    def _setup_file_monitor(self):
        try:
            from gi.repository import Gio
            f = Gio.File.new_for_path(CONFIG_PATH)
            self._file_monitor = f.monitor_file(Gio.FileMonitorFlags.NONE, None)
            if self._file_monitor:
                self._file_monitor.connect("changed", self._on_config_file_changed)
        except Exception as e:
            pass

    def _on_config_file_changed(self, monitor, file, other_file, event_type):
        try:
            from gi.repository import Gio, GLib
            if event_type in (Gio.FileMonitorEvent.CHANGES_DONE_HINT, Gio.FileMonitorEvent.CHANGED):
                old_lang = self._current_lang
                self._load_from_config()
                if self._current_lang != old_lang:
                    for listener in list(self._listeners):
                        try:
                            GLib.idle_add(listener, self._current_lang)
                        except Exception as e:
                            print(f"[i18n] listener callback error: {e}")
        except Exception:
            pass

    def _load_from_config(self):
        try:
            from src.config import config
            config.load()
            saved_lang = config.get("language")
            if saved_lang:
                self._current_lang = saved_lang
            saved_prefs = config.get("preferred_languages")
            if saved_prefs and isinstance(saved_prefs, list):
                self._preferred_languages = saved_prefs
            elif saved_lang:
                self._preferred_languages = [saved_lang, "en"] if saved_lang != "en" else ["en"]
            else:
                sys_lang = os.environ.get("LANG", "vi_VN.UTF-8").split(".")[0].split("_")[0]
                if sys_lang:
                    self._current_lang = sys_lang
        except Exception:
            self._current_lang = "vi"

    def get_current_language(self) -> str:
        """Returns the active language code, e.g. 'vi', 'en', 'fr'."""
        return self._current_lang

    def get_current_language_info(self) -> LanguageInfo:
        """Returns the full LanguageInfo for current language."""
        lang_info = find_language(self._current_lang)
        if not lang_info:
            all_langs = get_all_world_languages()
            lang_info = all_langs[0]
        return lang_info

    def get_preferred_languages(self) -> List[LanguageInfo]:
        """Returns list of LanguageInfo objects for preferred languages."""
        result = []
        for code in self._preferred_languages:
            info = find_language(code)
            if info:
                result.append(info)
        if not result:
            curr = self.get_current_language_info()
            result = [curr]
        return result

    def add_preferred_language(self, code: str, make_primary: bool = False):
        """Adds a language to user's preferred languages list."""
        clean = code.strip()
        if clean in self._preferred_languages:
            self._preferred_languages.remove(clean)
        if make_primary:
            self._preferred_languages.insert(0, clean)
            self.set_language(clean, apply_system=True)
        else:
            self._preferred_languages.append(clean)
            self._save_config()

    def remove_preferred_language(self, code: str):
        """Removes a language from preferred list (cannot remove primary)."""
        clean = code.strip()
        if clean in self._preferred_languages and len(self._preferred_languages) > 1:
            self._preferred_languages.remove(clean)
            if self._current_lang == clean:
                self.set_language(self._preferred_languages[0], apply_system=True)
            else:
                self._save_config()

    def set_language(self, lang_code: str, apply_system: bool = True) -> bool:
        """
        Switches the active language across macOS apps and the Ubuntu OS.
        """
        info = find_language(lang_code)
        target_code = info.code if info else lang_code
        self._current_lang = target_code

        # Ensure primary in preferred list
        if target_code in self._preferred_languages:
            self._preferred_languages.remove(target_code)
        self._preferred_languages.insert(0, target_code)

        # 1. Save to config.json
        self._save_config()

        # 2. Apply system-wide locale if requested
        if apply_system and info:
            from src.utils.system_locale import apply_system_language
            apply_system_language(info.locale, info.code)

        # 3. Notify running Dynamic Island instance via IPC
        try:
            from src.ipc import send_command
            send_command(f"set-language {target_code}")
        except Exception:
            pass

        # 4. Invoke all registered in-process listeners
        for listener in list(self._listeners):
            try:
                listener(target_code)
            except Exception as e:
                print(f"[i18n] listener callback error: {e}")

        return True

    def _save_config(self):
        try:
            from src.config import config
            config.set("language", self._current_lang)
            config.set("preferred_languages", self._preferred_languages)
        except Exception as e:
            print(f"[i18n] save config error: {e}")

    def add_listener(self, callback: Callable[[str], None]):
        """Registers a callback when language changes."""
        if callback not in self._listeners:
            self._listeners.append(callback)

    def remove_listener(self, callback: Callable[[str], None]):
        if callback in self._listeners:
            self._listeners.remove(callback)

    def translate(self, key: str, default: Optional[str] = None, **kwargs) -> str:
        """Translates a key with fallback: current -> en -> vi -> default -> key."""
        lang = self._current_lang
        # Try the exact locale first, then its base language.  This keeps
        # locale variants (for example fr_FR or pt_BR) in one language
        # instead of silently mixing in the default language.
        candidates = [lang]
        if "_" in lang:
            candidates.append(lang.split("_", 1)[0])
        for candidate in candidates:
            trans_dict = TRANSLATIONS.get(candidate)
            if trans_dict and key in trans_dict:
                text = trans_dict[key]
                return text.format(**kwargs) if kwargs else text

        # Fallback to English
        en_dict = TRANSLATIONS.get("en", {})
        if key in en_dict:
            text = en_dict[key]
            return text.format(**kwargs) if kwargs else text

        # Fallback to Vietnamese
        vi_dict = TRANSLATIONS.get("vi", {})
        if key in vi_dict:
            text = vi_dict[key]
            return text.format(**kwargs) if kwargs else text

        if default is not None:
            return default.format(**kwargs) if kwargs else default

        return key.format(**kwargs) if kwargs else key


_I18N_INSTANCE = I18nManager()

def get_i18n() -> I18nManager:
    return _I18N_INSTANCE

