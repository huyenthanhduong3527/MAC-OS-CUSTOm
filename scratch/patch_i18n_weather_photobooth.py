def patch_i18n():
    with open(TARGET_PATH, "r", encoding="utf-8") as f:
        content = f.read()

    # 1. Update each language dictionary inside TRANSLATIONS
    for lang, kv_map in NEW_TRANSLATIONS.items():
        # Find `"lang": {`
        marker = f'    "{lang}": {{\n'
        idx = content.find(marker)
        if idx == -1:
            print(f"Warning: could not find {marker}")
            continue

        insert_pos = idx + len(marker)
        lines = []
        for k, v in kv_map.items():
            # Check if key already exists in this lang
            if f'"{k}":' in content[idx:idx+15000]:
                continue
            v_escaped = v.replace('"', '\\"')
            lines.append(f'        "{k}": "{v_escaped}",\n')

        if lines:
            insertion = "".join(lines)
            content = content[:insert_pos] + insertion + content[insert_pos:]
            print(f"Added {len(lines)} keys to '{lang}' dictionary.")

    # 2. Add Gio.FileMonitor support in I18nManager
    if "_file_monitor" not in content:
        target_init = """        self._listeners: List[Callable[[str], None]] = []
        self._load_config()"""
        replacement_init = """        self._listeners: List[Callable[[str], None]] = []
        self._file_monitor = None
        self._load_config()
        self._setup_config_monitor()"""
        if target_init in content:
            content = content.replace(target_init, replacement_init)
            print("Added _setup_config_monitor call to I18nManager.__init__")

        monitor_methods = '''    def _setup_config_monitor(self):
        """Monitors config.json for live changes from other processes (e.g. Settings window)."""
        try:
            from gi.repository import Gio
            if os.path.exists(CONFIG_PATH):
                f = Gio.File.new_for_path(CONFIG_PATH)
                self._file_monitor = f.monitor_file(Gio.FileMonitorFlags.NONE, None)
                self._file_monitor.connect("changed", self._on_config_file_event)
        except Exception as e:
            self._file_monitor = None

    def _on_config_file_event(self, monitor, file, other_file, event_type):
        try:
            from gi.repository import Gio
            if event_type in (Gio.FileMonitorEvent.CHANGED, Gio.FileMonitorEvent.CHANGES_DONE_HINT):
                self._check_external_config_update()
        except Exception:
            pass

    def _check_external_config_update(self):
        try:
            if not os.path.exists(CONFIG_PATH):
                return
            with open(CONFIG_PATH, "r", encoding="utf-8") as f:
                data = json.load(f)
            new_lang = data.get("language")
            if new_lang and new_lang != self._current_lang:
                print(f"[i18n] Detected external language change: {self._current_lang} -> {new_lang}")
                self._current_lang = new_lang
                self._preferred_languages = data.get("preferred_languages", [new_lang, "en"])
                for listener in list(self._listeners):
                    try:
                        listener(new_lang)
                    except Exception as err:
                        print(f"[i18n] External change listener error: {err}")
        except Exception as e:
            pass

'''
        # Insert before `def _load_config(self):`
        pos = content.find("    def _load_config(self):")
        if pos != -1:
            content = content[:pos] + monitor_methods + content[pos:]
            print("Added config monitor methods to I18nManager")

    with open(TARGET_PATH, "w", encoding="utf-8") as f:
        f.write(content)
    print("Successfully patched i18n.py!")

if __name__ == "__main__":
    patch_i18n()
